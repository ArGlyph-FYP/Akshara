export interface SiCriterion {
  /** Matches Criterion.key and the key in Rating.criterionScores (a1 … a8, a6a, a6b, a6c). */
  key: string;
  code: string;
  labelEn: string;
  label: string;
  /** The test question. */
  question: string;
  /** "What to judge". */
  lookFor: string;
  /** What the criterion does not judge, and where that goes. */
  notJudged: string;
  /** level: five options (Excellent … Very weak); count: four options (None … Many). */
  kind: "level" | "count";
  /** Option descriptions, in the order shown (best first). */
  options: string[];
  /** A6a–A6c sit under the A6 heading. */
  group?: "a6";
}

export interface Option {
  value: number;
  name: string;
  description: string;
}

/** The options of a criterion in display order, with the value each one stores. */
export function optionsFor(c: SiCriterion): Option[] {
  return c.options.map((description, i) =>
    c.kind === "level"
      ? { value: 5 - i, name: LEVEL_NAMES[i], description }
      : { value: i, name: `${i}: ${COUNT_NAMES[i]}`, description },
  );
}

/** The name of a stored value, e.g. 4 → "හොඳයි" for a level criterion. */
export const valueName = (c: SiCriterion, v: number) => optionsFor(c).find((o) => o.value === v)?.name ?? String(v);

